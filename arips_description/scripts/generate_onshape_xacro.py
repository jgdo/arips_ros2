#!/usr/bin/env python3
"""Turn the raw Onshape URDF export into arips_onshape.urdf.xacro.

The raw export is used as is (it is replaced on every export). This script applies the
changes Onshape cannot export:
- removes the "root" link and "fixed_node_to_root_joint" Onshape sometimes adds
- adds collision elements (copies of the visuals)
- adds mimic tags
- makes some values configurable through xacro args

Usage: generate_onshape_xacro.py <raw_urdf> <output_xacro>
"""

import copy
import sys
import xml.etree.ElementTree as ET

XACRO_NS = 'http://www.ros.org/wiki/xacro'

REMOVED_LINKS = ['root']
REMOVED_JOINTS = ['fixed_node_to_root_joint']

# Gazebo drives with its own wheel joints, so the fixed wheel meshes must not touch the floor
NO_SIM_COLLISION_LINKS = ['left_wheel', 'right_wheel']

# Gazebo uses the effort limit as the force that holds the joint in place, the sim raises it
ARM_EFFORT_JOINTS = ['joint_2', 'joint_3', 'joint_4']

# mimic joint: (mimicked joint, multiplier, offset)
MIMIC_JOINTS = {
    'joint_claw_passive': ('joint_claw_active', -1.0, 0.0),
}

XACRO_ARGS = [
    ('sim', 'false'),
    ('arm_joint_effort', '1'),
]


def find_named(root, tag, name):
    element = root.find(f"{tag}[@name='{name}']")
    if element is None:
        raise RuntimeError(f"Onshape export has no {tag} named '{name}'")
    return element


def add_collisions(root):
    for link in root.findall('link'):
        if link.find('collision') is not None:
            continue
        for visual in link.findall('visual'):
            collision = ET.Element('collision')
            for child in ('origin', 'geometry'):
                if visual.find(child) is not None:
                    collision.append(copy.deepcopy(visual.find(child)))
            if link.get('name') in NO_SIM_COLLISION_LINKS:
                wrapper = ET.SubElement(link, f'{{{XACRO_NS}}}unless', value='$(arg sim)')
                wrapper.append(collision)
            else:
                link.append(collision)


def generate(raw_path, output_path):
    ET.register_namespace('xacro', XACRO_NS)
    root = ET.parse(raw_path).getroot()

    for name in REMOVED_LINKS:
        element = root.find(f"link[@name='{name}']")
        if element is not None:
            root.remove(element)
    for name in REMOVED_JOINTS:
        element = root.find(f"joint[@name='{name}']")
        if element is not None:
            root.remove(element)

    add_collisions(root)

    for name in ARM_EFFORT_JOINTS:
        find_named(root, 'joint', name).find('limit').set('effort', '$(arg arm_joint_effort)')

    for name, (mimicked, multiplier, offset) in MIMIC_JOINTS.items():
        find_named(root, 'joint', mimicked)
        ET.SubElement(find_named(root, 'joint', name), 'mimic',
                      joint=mimicked, multiplier=str(multiplier), offset=str(offset))

    for index, (name, default) in enumerate(XACRO_ARGS):
        root.insert(index, ET.Element(f'{{{XACRO_NS}}}arg', name=name, default=default))

    root.set('name', 'arips')
    ET.indent(root, space='    ')
    with open(output_path, 'w') as f:
        f.write('<?xml version="1.0"?>\n')
        f.write(f'<!-- Generated by arips_description/scripts/generate_onshape_xacro.py from '
                f'{raw_path.rsplit("/", 1)[-1]}, do not edit -->\n')
        f.write(ET.tostring(root, encoding='unicode'))
        f.write('\n')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    generate(sys.argv[1], sys.argv[2])
